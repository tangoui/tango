// Builds dist/ (ESM + IIFE + .d.ts) and refreshes the Go-embedded copy of the
// IIFE in runtimejs/tango.iife.js.
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const dist = join(root, "dist");
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

const common = { bundle: true, target: "es2020", logLevel: "warning", legalComments: "none" };

await build({
  ...common,
  entryPoints: [join(root, "src/index.ts")],
  outfile: join(dist, "index.js"),
  format: "esm",
  sourcemap: true,
});

await build({
  ...common,
  entryPoints: [join(root, "src/iife.ts")],
  outfile: join(dist, "tango.iife.js"),
  format: "iife",
  minify: true,
});

const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc");
execFileSync(process.execPath, [tsc, "-p", root, "--emitDeclarationOnly"], { stdio: "inherit" });

const iife = readFileSync(join(dist, "tango.iife.js"), "utf8");
writeFileSync(
  join(root, "runtimejs/tango.iife.js"),
  "// Code generated by runtime-js/build.mjs from runtime-js/src; DO NOT EDIT.\n" + iife,
);
console.log(`built dist/ and runtimejs/tango.iife.js (${iife.length} bytes)`);
