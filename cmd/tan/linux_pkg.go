// Linux package formats for tan package -format. Without -format a Linux
// target gets tar and appimage (packageLinux).
var linuxFormatNames = []string{"tar", "appimage", "deb", "rpm", "flatpak"}

// linuxFormats splits -format into its names, without duplicates.
func linuxFormats(format string) []string {
	var fs []string
	for f := range strings.SplitSeq(format, ",") {
		if f = strings.ToLower(strings.TrimSpace(f)); f != "" && !slices.Contains(fs, f) {
			fs = append(fs, f)
		}
	}
	return fs
}

// checkLinuxFormats validates a -format other than "" and "msix".
func checkLinuxFormats(format string, ts []target) error {
	fs := linuxFormats(format)
	for _, f := range fs {
		if !slices.Contains(linuxFormatNames, f) {
			return fmt.Errorf("unknown -format %q (want msix for Windows; tar, appimage, deb, rpm or flatpak, comma-separated, for Linux; or nothing for the platform default)", f)
		}
	}
	if len(fs) == 0 {
		return fmt.Errorf("-format %q names no format", format)
	}
	for _, t := range ts {
		if t.OS != "linux" {
			return fmt.Errorf("-format %s is for Linux targets, not %s", strings.Join(fs, ","), t)
		}
	}
	return nil
}

// packageLinuxFormats makes the Linux packages named in formats.
func packageLinuxFormats(ctx context.Context, cfg *Config, a artifact, formats []string) ([]string, error) {
	icons, err := linuxIconTree(cfg)
	if err != nil {
		return nil, err
	}
	var made []string
	for _, f := range formats {
		var m []string
		switch f {
		case "tar":
			var tgz string
			tgz, err = linuxTarball(cfg, a, icons)
			m = []string{tgz}
		case "appimage":
			m, err = linuxAppImage(cfg, a, icons)
		case "deb":
			var deb string
			deb, err = packageDeb(cfg, a, icons) // deb.go
			m = []string{deb}
		case "rpm":
			var rpm string
			rpm, err = packageRPM(cfg, a, icons) // rpm.go
			m = []string{rpm}
		case "flatpak":
			m, err = packageFlatpak(ctx, cfg, a, icons) // flatpak.go
		}
		made = append(made, m...)
		if err != nil {
			return made, fmt.Errorf("%s: %w", f, err)
		}
	}
	return made, nil
}

// sysFile is a file a deb or rpm installs.
type sysFile struct {
	path string // absolute, e.g. /usr/bin/Hello
	data []byte
	mode int64 // permission bits
}

// linuxSystemFiles lists what the deb and rpm install, sorted by path: the
// program in /usr/bin, the .desktop file named after the app id (the
// Wayland app id GTK uses when the app sets tango.Options.ID), the hicolor
// icons, and the MIME definitions.
func linuxSystemFiles(cfg *Config, a artifact, icons map[string][]byte) ([]sysFile, error) {
	exe, err := os.ReadFile(a.exe)
	if err != nil {
		return nil, err
	}
	files := []sysFile{
		{path: "/usr/bin/" + cfg.Exe(), data: exe, mode: 0o755},
		{path: "/usr/share/applications/" + cfg.ID + ".desktop", data: []byte(desktopEntry(cfg)), mode: 0o644},
	}
	for p, b := range icons {
		files = append(files, sysFile{path: "/usr/share/" + p, data: b, mode: 0o644})
	}
	if x := mimePackage(cfg); x != nil {
		files = append(files, sysFile{path: "/usr/share/mime/packages/" + cfg.ID + ".xml", data: x, mode: 0o644})
	}
	slices.SortFunc(files, func(a, b sysFile) int { return strings.Compare(a.path, b.path) })
	return files, nil
}

// linuxParentDirs lists the directories above files, parents first,
// without "/".
func linuxParentDirs(files []sysFile) []string {
	var dirs []string
	for _, f := range files {
		for d := path.Dir(f.path); d != "/"; d = path.Dir(d) {
			if !slices.Contains(dirs, d) {
				dirs = append(dirs, d)
			}
		}
	}
	slices.Sort(dirs) // a parent sorts before its children
	return dirs
}

// linuxCacheScript refreshes the desktop, MIME and icon caches, each only
// when its tool is installed; deb maintainer scripts and rpm scriptlets
// run it after install and after removal.
func linuxCacheScript(files []sysFile) string {
	has := func(prefix string) bool {
		return slices.ContainsFunc(files, func(f sysFile) bool { return strings.HasPrefix(f.path, prefix) })
	}
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by tan package: refresh the desktop, MIME and icon caches.\nset -e\n")
	b.WriteString("if command -v update-desktop-database >/dev/null 2>&1; then\n  update-desktop-database -q /usr/share/applications || true\nfi\n")
	if has("/usr/share/mime/") {
		b.WriteString("if command -v update-mime-database >/dev/null 2>&1; then\n  update-mime-database /usr/share/mime || true\nfi\n")
	}
	if has("/usr/share/icons/hicolor/") {
		b.WriteString("if command -v gtk-update-icon-cache >/dev/null 2>&1; then\n  gtk-update-icon-cache -q -t -f /usr/share/icons/hicolor || true\nfi\n")
	}
	b.WriteString("exit 0\n")
	return b.String()
}

// linuxPackageName is "linux.package", or the name in lower case with
// words joined by '-', or, when that is under two characters, the id in
// lower case: a valid Debian (Policy 5.6.1) and rpm package name.
func linuxPackageName(cfg *Config) string {
	if cfg.Linux.Package != "" {
		return cfg.Linux.Package
	}
	if s := slug(cfg.Name); len(s) >= 2 {
		return s
	}
	return strings.ToLower(cfg.ID)
}

// linuxPackageVersion maps a SemVer-style version to a deb upstream version
// or an rpm Version: '-' starts a pre-release, which must sort before the
// release, so it becomes '~' (both dpkg and rpm sort '~' first, and
// neither allows '-' there); '-' in build metadata after '+' becomes '.'.
// 1.2.3-rc.1+b-5 → 1.2.3~rc.1+b.5.
func linuxPackageVersion(v string) string {
	core, build, hasBuild := strings.Cut(v, "+")
	core = strings.ReplaceAll(core, "-", "~")
	if hasBuild {
		return core + "+" + strings.ReplaceAll(build, "-", ".")
	}
	return core
}

// linuxSummary and linuxDescription split "linux.description": the first
// line is the summary, the rest (possibly empty) the long description.
func linuxSummary(cfg *Config) string {
	first, _, _ := strings.Cut(strings.TrimSpace(cfg.Linux.Description), "\n")
	return cmp.Or(strings.TrimSpace(first), cfg.Name)
}

// oneLine replaces control characters (newlines among them) with spaces,
// so a value from tan.json cannot start a new field in a deb control file
// or an rpm header string. validate rejects most of these already.
func oneLine(s string) string {
	return strings.Map(func(r rune) rune {
		if unicode.IsControl(r) {
			return ' '
		}
		return r
	}, s)
}

func linuxDescription(cfg *Config) string {
	_, rest, _ := strings.Cut(strings.TrimSpace(cfg.Linux.Description), "\n")
	return strings.TrimSpace(rest)
}

// packageTime is the modification time recorded in packages:
// $SOURCE_DATE_EPOCH when set (reproducible builds), else now.
func packageTime() time.Time {
	if s := os.Getenv("SOURCE_DATE_EPOCH"); s != "" {
		if n, err := strconv.ParseInt(s, 10, 64); err == nil {
			return time.Unix(n, 0).UTC()
		}
	}
	return time.Now().UTC().Truncate(time.Second)
}
