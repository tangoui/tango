// Command tanshader compiles a Go shader package (written against
// internal/render/shader/sl) to Metal Shading Language, HLSL and GLSL.
//
// Usage:
//
//	tanshader -pkg dir -out dir
//
// The package in -pkg holds one vertex/fragment entry pair (see
// internal/render/shader/front). The output is written to -out as <name>.metal (see
// internal/render/shader/msl), <name>.hlsl (shader model 5.0, also
// SM4-compatible, see internal/render/shader/hlsl), and <name>.vert and <name>.frag
// (the GLSL 3.30 core vertex and fragment shaders, see internal/render/shader/glsl),
// where name is the base name of the .go file that declares the
// //sl:vertex function, and <name>_layout.go (Go package -package; by default the
// package of the other .go files in -out, else the directory name), the
// host side of the buffer layouts:
//
//   - <Name><In>Stride and <Name><In>Attrs: the size of the vertex input
//     struct In (the per-instance vertex buffer stride) and its attributes
//     by location (byte offset, scalar kind, component count), for the
//     device's vertex descriptor (Metal) or input layout (Direct3D 11);
//   - TextureDesc and <Name>Textures: the shader's textures by binding with
//     their filter, for the samplers a Direct3D 11 device creates (Metal
//     declares them in the shader);
//   - compile-time assertions that the vertex input struct and every
//     uniform struct still have the size and field offsets the shader was
//     generated for (the front end checked that they match the MSL,
//     HLSL and GLSL std140 layouts), so changing a struct without running go generate breaks
//     the build instead of silently misaligning GPU reads. Unexported
//     structs or fields of another package cannot be asserted and are
//     listed in a comment instead.
//
// All files start with "// Code generated by tanshader. DO NOT EDIT."
// (the GLSL files on their second line, after the #version directive that
// GLSL requires first) and are rewritten only when their content changes.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"

	"github.com/tangoui/tango/internal/render/shader/front"
	"github.com/tangoui/tango/internal/render/shader/glsl"
	"github.com/tangoui/tango/internal/render/shader/hlsl"
	"github.com/tangoui/tango/internal/render/shader/msl"
)

const header = "// Code generated by tanshader. DO NOT EDIT.\n"

func main() {
	pkg := flag.String("pkg", ".", "directory of the shader package")
	out := flag.String("out", ".", "output directory")
	gopkg := flag.String("package", "", "Go package name of the generated layout file (default: the package in -out)")
	flag.Parse()
	if flag.NArg() > 0 {
		fmt.Fprintln(os.Stderr, "usage: tanshader -pkg dir -out dir [-package name]")
		os.Exit(2)
	}
	if err := run(*pkg, *out, *gopkg); err != nil {
		fmt.Fprintln(os.Stderr, "tanshader:", err)
		os.Exit(1)
	}
}

func run(pkg, out, gopkg string) error {
	m, err := front.Load(pkg)
	if err != nil {
		return err
	}
	src, err := msl.Generate(m)
	if err != nil {
		return err
	}
	hsrc, err := hlsl.Generate(m)
	if err != nil {
		return err
	}
	vsrc, fsrc, err := glsl.Generate(m, glsl.GLSL330)
	if err != nil {
		return err
	}
	name, shaderPkg, err := vertexFile(pkg)
	if err != nil {
		return err
	}
	base := strings.TrimSuffix(name, ".go")
	if err := writeIfChanged(filepath.Join(out, base+".metal"), []byte(header+stripHeader(src))); err != nil {
		return err
	}
	if err := writeIfChanged(filepath.Join(out, base+".hlsl"), []byte(header+stripHeader(hsrc))); err != nil {
		return err
	}
	if err := writeIfChanged(filepath.Join(out, base+".vert"), []byte(glslHeader(vsrc))); err != nil {
		return err
	}
	if err := writeIfChanged(filepath.Join(out, base+".frag"), []byte(glslHeader(fsrc))); err != nil {
		return err
	}
	if gopkg == "" {
		if gopkg, err = outPackage(out); err != nil {
			return err
		}
	}
	qual, imp := shaderPkg+".", ""
	if same, err := sameDir(pkg, out); err != nil {
		return err
	} else if same {
		qual = ""
	} else if imp, err = importPath(pkg); err != nil {
		return err
	}
	lay, err := layoutFile(m, layoutParams{base: base, pkg: gopkg, qual: qual, imp: imp})
	if err != nil {
		return err
	}
	return writeIfChanged(filepath.Join(out, base+"_layout.go"), lay)
}

func writeIfChanged(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return nil
	}
	return os.WriteFile(path, data, 0o644)
}

// stripHeader removes the backend's own "// Code generated" first line so
// the file carries a single header naming this command.
func stripHeader(src string) string {
	if strings.HasPrefix(src, "// Code generated ") {
		if i := strings.IndexByte(src, '\n'); i >= 0 {
			return src[i+1:]
		}
	}
	return src
}

// glslHeader replaces the GLSL backend's "// Code generated" line, which
// follows the #version line, with this command's header, keeping #version
// first.
func glslHeader(src string) string {
	version, rest, _ := strings.Cut(src, "\n")
	return version + "\n" + header + stripHeader(rest)
}

// vertexFile returns the base name of the non-test .go file in dir whose
// function marked //sl:vertex, and its package name. front.Load has
// already checked that exactly one exists.
func vertexFile(dir string) (string, string, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return "", "", err
	}
	fset := token.NewFileSet()
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		af, err := parser.ParseFile(fset, f, nil, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			return "", "", err
		}
		for _, d := range af.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Doc == nil {
				continue
			}
			for _, c := range fd.Doc.List {
				if strings.TrimSpace(c.Text) == "//sl:vertex" {
					return filepath.Base(f), af.Name.Name, nil
				}
			}
		}
	}
	return "", "", fmt.Errorf("no //sl:vertex function in %s", dir)
}
