// Command shadcngen writes ui/theme/shadcn_data.go from the shadcn/ui v4
// theme registry (apps/v4/registry/themes.ts) and the Tailwind CSS v4 gray
// scales (theme.css). See docs/specs/align/README.md for the versions.
//
//	go run ./internal/cmd/shadcngen \
//	  -themes /tmp/tango-ref/shadcn-ui/apps/v4/registry/themes.ts \
//	  -css /tmp/tango-ref/tw/package/theme.css \
//	  -o ui/theme/shadcn_data.go \
//	  -source "shadcn-ui/ui@e62c943, tailwindcss@4.3.5"
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
	"strings"
)

// grayFamilies are the Tailwind families shadcn bases are built from
// (slate and gray are the legacy v3 bases).
var grayFamilies = []string{"neutral", "stone", "zinc", "mauve", "olive", "mist", "taupe", "slate", "gray"}

var steps = []string{"50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"}

type theme struct {
	name        string
	light, dark map[string]string
}

var (
	nameRe = regexp.MustCompile(`^\s*name:\s*"([^"]+)"`)
	varRe  = regexp.MustCompile(`^\s*"?([a-z0-9-]+)"?:\s*"([^"]*)",?\s*$`)
	modeRe = regexp.MustCompile(`^\s*(light|dark):\s*\{`)
	cssRe  = regexp.MustCompile(`^\s*--color-([a-z]+)-(\d+):\s*([^;]+);`)
)

func parseThemes(src []byte) ([]theme, error) {
	var out []theme
	var mode map[string]string
	sc := bufio.NewScanner(bytes.NewReader(src))
	for sc.Scan() {
		line := sc.Text()
		if m := nameRe.FindStringSubmatch(line); m != nil {
			out = append(out, theme{name: m[1], light: map[string]string{}, dark: map[string]string{}})
			mode = nil
			continue
		}
		if len(out) == 0 {
			continue
		}
		cur := &out[len(out)-1]
		if m := modeRe.FindStringSubmatch(line); m != nil {
			mode = cur.light
			if m[1] == "dark" {
				mode = cur.dark
			}
			continue
		}
		if mode == nil {
			continue
		}
		if strings.TrimSpace(line) == "}," || strings.TrimSpace(line) == "}" {
			mode = nil
			continue
		}
		if m := varRe.FindStringSubmatch(line); m != nil && m[1] != "radius" {
			mode[m[1]] = m[2]
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no themes found")
	}
	return out, sc.Err()
}

func parseScales(src []byte) map[string]map[string]string {
	keep := map[string]bool{}
	for _, f := range grayFamilies {
		keep[f] = true
	}
	out := map[string]map[string]string{}
	sc := bufio.NewScanner(bytes.NewReader(src))
	for sc.Scan() {
		m := cssRe.FindStringSubmatch(sc.Text())
		if m == nil || !keep[m[1]] {
			continue
		}
		if out[m[1]] == nil {
			out[m[1]] = map[string]string{}
		}
		out[m[1]][m[2]] = strings.TrimSpace(m[3])
	}
	return out
}

func generate(themesTS, themeCSS []byte, source string) ([]byte, error) {
	themes, err := parseThemes(themesTS)
	if err != nil {
		return nil, err
	}
	scales := parseScales(themeCSS)
	var bases, colors []string
	for _, t := range themes {
		if _, ok := t.light["background"]; ok {
			bases = append(bases, t.name)
		} else {
			colors = append(colors, t.name)
		}
	}
	for _, b := range bases {
		if scales[b] == nil {
			return nil, fmt.Errorf("theme.css has no --color-%s-* scale for base %q", b, b)
		}
	}
	families := make([]string, 0, len(scales))
	for f, s := range scales {
		for _, st := range steps {
			if s[st] == "" {
				return nil, fmt.Errorf("theme.css lacks --color-%s-%s", f, st)
			}
		}
		families = append(families, f)
	}
	sort.Strings(families)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/cmd/shadcngen; DO NOT EDIT.\n// Source: %s.\n\npackage theme\n\n", source)
	fmt.Fprintf(&b, "// shadcnBaseNames are the shadcn/ui v4 base themes, in registry order.\nvar shadcnBaseNames = %#v\n\n", bases)
	fmt.Fprintf(&b, "// shadcnColorNames are the shadcn/ui v4 color themes, in registry order.\nvar shadcnColorNames = %#v\n\n", colors)
	b.WriteString("// shadcnThemeVars are the CSS variables of each shadcn/ui v4 theme.\nvar shadcnThemeVars = map[string]struct{ light, dark map[string]string }{\n")
	sorted := append([]theme(nil), themes...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].name < sorted[j].name })
	for _, t := range sorted {
		fmt.Fprintf(&b, "%q: {\nlight: %s,\ndark: %s,\n},\n", t.name, mapLit(t.light), mapLit(t.dark))
	}
	b.WriteString("}\n\n// tailwindV4Scales are the Tailwind CSS v4 gray families, 50 … 950.\nvar tailwindV4Scales = map[string][11]string{\n")
	for _, f := range families {
		vals := make([]string, len(steps))
		for i, st := range steps {
			vals[i] = fmt.Sprintf("%q", scales[f][st])
		}
		fmt.Fprintf(&b, "%q: {%s},\n", f, strings.Join(vals, ", "))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func mapLit(m map[string]string) string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%q: %q,\n", k, m[k])
	}
	b.WriteString("}")
	return b.String()
}

func main() {
	themesPath := flag.String("themes", "", "path to shadcn apps/v4/registry/themes.ts")
	cssPath := flag.String("css", "", "path to tailwindcss theme.css")
	outPath := flag.String("o", "ui/theme/shadcn_data.go", "output file")
	source := flag.String("source", "", "source versions recorded in the header")
	flag.Parse()
	ts, err := os.ReadFile(*themesPath)
	if err != nil {
		log.Fatal(err)
	}
	css, err := os.ReadFile(*cssPath)
	if err != nil {
		log.Fatal(err)
	}
	out, err := generate(ts, css, *source)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*outPath, out, 0o644); err != nil {
		log.Fatal(err)
	}
}
