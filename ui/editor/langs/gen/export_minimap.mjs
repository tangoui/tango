// Dev-time exporter for the minimap's character shapes (ui/editor
// minimap_chars.go): the prebaked glyph alpha data of monaco-editor@0.56.0
// (editor/browser/viewParts/minimap/minimapPreBaked.js, scales 1 and 2,
// the scales Monaco's minimap renders text at with minimap.scale 1 on
// 1x and 2x displays) written to ../../minimap_chars_gen.go, and a few
// lines rendered by Monaco's own MinimapCharRenderer.renderChar (both
// fonts, opaque and translucent minimap.foregroundOpacity) written to
// ../../testdata/minimap/render.json for TestMinimapCharacters.
//
// Usage: npm install && node export_minimap.mjs (no network). It exits 1
// without writing anything when the data sizes differ (the pinned package
// changed).

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const MONACO_VERSION = '0.56.0';
const CHAR_COUNT = 96; // Monaco's Constants.CHAR_COUNT: U+0020–U+007E and U+FFFD
const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, 'node_modules', 'monaco-editor', 'esm', 'vs', 'editor', 'browser', 'viewParts', 'minimap');
const outFile = path.resolve(here, '..', '..', 'minimap_chars_gen.go');
const renderFile = path.resolve(here, '..', '..', 'testdata', 'minimap', 'render.json');

// RENDER_CASES are rendered with renderChar into an RGBA buffer cleared to
// the background, one character per cell as Monaco's _renderLine places
// them (spaces skipped).
const RENDER_CASES = [
	{ text: 'a.', color: [86, 156, 214], bg: [30, 30, 30], bgAlpha: 255, fgAlpha: 255, light: false },
	{ text: 'Wi;~', color: [0, 0, 255], bg: [255, 255, 255], bgAlpha: 255, fgAlpha: 255, light: true },
	{ text: 'x é~', color: [206, 145, 120], bg: [30, 30, 30], bgAlpha: 255, fgAlpha: 192, light: false },
];

async function main() {
	const { prebakedMiniMaps } = await import(pathToFileURL(path.join(dir, 'minimapPreBaked.js')).href);
	const { MinimapCharRenderer } = await import(pathToFileURL(path.join(dir, 'minimapCharRenderer.js')).href);
	const data = {};
	for (const scale of [1, 2]) {
		const d = prebakedMiniMaps[scale]();
		const want = CHAR_COUNT * scale * 2 * scale;
		if (d.length !== want) throw new Error(`prebaked ${scale}x: ${d.length} bytes, want ${want}`);
		data[scale] = d;
	}
	const renders = [];
	for (const scale of [1, 2]) {
		const r = new MinimapCharRenderer(data[scale], scale);
		for (const c of RENDER_CASES) {
			const cw = scale, ch = 2 * scale;
			const width = c.text.length * cw;
			const target = { width, height: ch, data: new Uint8ClampedArray(width * ch * 4) };
			for (let i = 0; i < target.data.length; i += 4) target.data.set([...c.bg, c.bgAlpha], i);
			const color = { r: c.color[0], g: c.color[1], b: c.color[2] };
			const bg = { r: c.bg[0], g: c.bg[1], b: c.bg[2] };
			for (let i = 0; i < c.text.length; i++) {
				const code = c.text.charCodeAt(i);
				if (code === 32) continue;
				r.renderChar(target, i * cw, 0, code, color, c.fgAlpha, bg, c.bgAlpha, scale, c.light, false);
			}
			renders.push({ scale, ...c, width, height: ch, rgba: [...target.data] });
		}
	}
	const rows = (bytes, per) => {
		let out = '';
		for (let i = 0; i < bytes.length; i += per) out += '\t' + [...bytes.slice(i, i + per)].map((n) => '0x' + n.toString(16).padStart(2, '0')).join(', ') + ',\n';
		return out;
	};
	const go = `// Code generated by ui/editor/langs/gen/export_minimap.mjs from monaco-editor@${MONACO_VERSION}'s
// editor/browser/viewParts/minimap/minimapPreBaked.js; DO NOT EDIT.
// Copyright (c) Microsoft Corporation, MIT License (see theme/NOTICE).

package editor

// minimapGlyphs1x and minimapGlyphs2x are Monaco's prebaked minimap
// character alphas (prebakedMiniMaps[1] and [2], decoded): for each of the
// ${CHAR_COUNT} characters U+0020–U+007E and U+FFFD in turn, a scale×2·scale
// cell (1×2 and 2×4 pixels) row by row.
var minimapGlyphs1x = [${CHAR_COUNT * 2}]byte{
${rows(data[1], 16)}}

var minimapGlyphs2x = [${CHAR_COUNT * 8}]byte{
${rows(data[2], 16)}}
`;
	fs.writeFileSync(outFile, go);
	execFileSync('gofmt', ['-w', outFile], { stdio: 'inherit' });
	fs.mkdirSync(path.dirname(renderFile), { recursive: true });
	fs.writeFileSync(renderFile, '[\n' + renders.map((r) => JSON.stringify(r)).join(',\n') + '\n]\n');
	console.log(`minimap: ${data[1].length} + ${data[2].length} glyph bytes, ${renders.length} renders; wrote ${path.relative(process.cwd(), outFile)} and ${path.relative(process.cwd(), renderFile)}`);
}

try {
	await main();
} catch (err) {
	console.error(err);
	process.exitCode = 1;
}
