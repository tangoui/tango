// Package antd is the complete Ant Design icon set (@ant-design/icons-svg,
// MIT; see LICENSE) in its three themes: Outlined, Filled and TwoTone,
// named like @ant-design/icons (SearchOutlined, CheckCircleFilled,
// CheckCircleTwoTone):
//
//	ui.Icon(c, antd.SearchOutlined)
//
// TwoTone icons paint their light parts in icon.DrawOpts.Secondary (by
// default the main color at 20% opacity).
//
// Every icon is a statically initialized variable, so a program links only
// the icons it references. Register makes the whole set reachable by name
// ("ant:" plus the file name and theme, e.g.
// icon.ByName("ant:search-outlined")).
//
// The icons are generated by internal/cmd/icongen; do not edit icons.go.
//
// Experimental: this package's API may change in any 0.x release (see
// docs/release.md, "API 稳定性"); icon names follow the upstream set and
// may change when it is updated.
package antd

import "github.com/tangoui/tango/ui/icon"

// Register registers every icon of the set with icon.ByName under its
// "ant:" name. It links the whole set into the program.
func Register() { icon.Register(All()...) }
