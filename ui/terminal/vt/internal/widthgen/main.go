// Command widthgen generates ui/terminal/vt/width_table.go from the
// Unicode Character Database.
//
// Usage:
//
//	go run ./internal/widthgen -data DIR [-o width_table.go]
//
// DIR must hold these three files directly (flat, no subdirectories),
// downloaded from:
//
//	https://www.unicode.org/Public/15.1.0/ucd/EastAsianWidth.txt
//	https://www.unicode.org/Public/15.1.0/ucd/emoji/emoji-data.txt
//	https://www.unicode.org/Public/15.1.0/ucd/extracted/DerivedGeneralCategory.txt
//
// Each file's header must name Unicode (or Emoji) version 15.1. The data
// files are not kept in the repository.
//
// The width rules follow xterm.js's unicode11 addon:
//
//   - General_Category Mn, Me or Cf, and a fixed list of zero-width code
//     points (ZWSP and friends, BOM, Hangul jungseong/jongseong): 0.
//   - East_Asian_Width W or F, or Emoji_Presentation=Yes: 2.
//   - Everything else: 1.
//
// Zero width wins over wide. C0/C1 controls are handled by Width itself.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

const (
	unicodeVersion = "15.1.0"
	emojiVersion   = "15.1" // as named in emoji-data.txt's header
)

// extraZero lists code points xterm.js treats as zero width in addition
// to Mn/Me/Cf.
var extraZero = [][2]rune{
	{0x1160, 0x11FF}, // Hangul jungseong and jongseong
	{0x200B, 0x200F},
	{0x2028, 0x202E},
	{0x2060, 0x206F},
	{0xFEFF, 0xFEFF},
}

// extraWide lists the ranges EastAsianWidth.txt's header says default to
// W even where unassigned.
var extraWide = [][2]rune{
	{0x3400, 0x4DBF},
	{0x4E00, 0x9FFF},
	{0xF900, 0xFAFF},
	{0x20000, 0x2FFFD},
	{0x30000, 0x3FFFD},
}

func main() {
	data := flag.String("data", "", "directory holding the Unicode data files")
	out := flag.String("o", "width_table.go", "output file")
	flag.Parse()
	if *data == "" {
		log.Fatal("widthgen: -data is required (download the UCD files from https://www.unicode.org/Public/" + unicodeVersion + "/ucd/)")
	}

	zero := map[rune]bool{}
	wide := map[rune]bool{}

	mustParse(filepath.Join(*data, "DerivedGeneralCategory.txt"), "-"+unicodeVersion+".txt", func(lo, hi rune, prop string) {
		if prop == "Mn" || prop == "Me" || prop == "Cf" {
			mark(zero, lo, hi)
		}
	})
	for _, r := range extraZero {
		mark(zero, r[0], r[1])
	}
	mustParse(filepath.Join(*data, "EastAsianWidth.txt"), "-"+unicodeVersion+".txt", func(lo, hi rune, prop string) {
		if prop == "W" || prop == "F" {
			mark(wide, lo, hi)
		}
	})
	for _, r := range extraWide {
		mark(wide, r[0], r[1])
	}
	mustParse(filepath.Join(*data, "emoji-data.txt"), "Emoji Version "+emojiVersion, func(lo, hi rune, prop string) {
		if prop == "Emoji_Presentation" {
			mark(wide, lo, hi)
		}
	})
	// Controls are answered by Width before the table lookup.
	for r := range zero {
		if r < 0xA0 {
			delete(zero, r)
		}
	}
	for r := range zero {
		delete(wide, r)
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by widthgen from Unicode %s; DO NOT EDIT.\n\n", unicodeVersion)
	buf.WriteString("package vt\n\n")
	fmt.Fprintf(&buf, "// unicodeVersion is the Unicode version the width tables come from.\nconst unicodeVersion = %q\n\n", unicodeVersion)
	writeTable(&buf, "zeroWidth", "zeroWidth lists code points of width 0, sorted.", ranges(zero))
	writeTable(&buf, "wideWidth", "wideWidth lists code points of width 2, sorted.", ranges(wide))
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("widthgen: format: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func mark(set map[rune]bool, lo, hi rune) {
	for r := lo; r <= hi; r++ {
		set[r] = true
	}
}

func ranges(set map[rune]bool) [][2]rune {
	rs := make([]rune, 0, len(set))
	for r := range set {
		rs = append(rs, r)
	}
	slices.Sort(rs)
	var out [][2]rune
	for _, r := range rs {
		if n := len(out); n > 0 && out[n-1][1] == r-1 {
			out[n-1][1] = r
			continue
		}
		out = append(out, [2]rune{r, r})
	}
	return out
}

func writeTable(buf *bytes.Buffer, name, doc string, rs [][2]rune) {
	fmt.Fprintf(buf, "// %s\nvar %s = []runeRange{\n", doc, name)
	for i, r := range rs {
		fmt.Fprintf(buf, "{0x%04X, 0x%04X},", r[0], r[1])
		if i%4 == 3 {
			buf.WriteByte('\n')
		}
	}
	buf.WriteString("\n}\n\n")
}

// mustParse calls fn for every "range ; property" line of a UCD file. The
// header (the comment lines before the first data line) must contain
// marker: "-15.1.0.txt" in the UCD files' first line, "Emoji Version 15.1"
// in emoji-data.txt.
func mustParse(path, marker string, fn func(lo, hi rune, prop string)) {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	header := true
	for n := 1; sc.Scan(); n++ {
		line := sc.Text()
		if header {
			if strings.Contains(line, marker) {
				header = false
			} else if !strings.HasPrefix(line, "#") && strings.TrimSpace(line) != "" {
				log.Fatalf("%s: header does not contain %q; want version %s data", path, marker, unicodeVersion)
			}
		}
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		if strings.TrimSpace(line) == "" {
			continue
		}
		field := strings.Split(line, ";")
		if len(field) < 2 {
			log.Fatalf("%s:%d: malformed line", path, n)
		}
		lo, hi, err := parseRange(strings.TrimSpace(field[0]))
		if err != nil {
			log.Fatalf("%s:%d: %v", path, n, err)
		}
		fn(lo, hi, strings.TrimSpace(field[1]))
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if header {
		log.Fatalf("%s: header does not contain %q; want version %s data", path, marker, unicodeVersion)
	}
}

func parseRange(s string) (lo, hi rune, err error) {
	a, b, isRange := strings.Cut(s, "..")
	l, err := strconv.ParseUint(a, 16, 32)
	if err != nil {
		return 0, 0, err
	}
	h := l
	if isRange {
		if h, err = strconv.ParseUint(b, 16, 32); err != nil {
			return 0, 0, err
		}
	}
	if h < l || h > 0x10FFFF {
		return 0, 0, fmt.Errorf("bad range %q", s)
	}
	return rune(l), rune(h), nil
}
